let CURRENT_LANG = localStorage.getItem("seva_lang") || "en";
function t(key) { return TRANSLATIONS[CURRENT_LANG][key] || key; }

function applyI18n() {
  document.querySelectorAll("[data-i18n]").forEach(el => {
    el.innerText = t(el.dataset.i18n);
  });
  document.querySelectorAll("[data-i18n-ph]").forEach(el => {
    el.placeholder = t(el.dataset.i18nPh);
  });
}

function setLanguage(lang) {
  CURRENT_LANG = lang;
  localStorage.setItem("seva_lang", lang);
  document.querySelectorAll(".lang-btn").forEach(b => b.classList.remove("active"));
  const activeBtn = document.querySelector(`.lang-btn[data-lang="${lang}"]`);
  if (activeBtn) activeBtn.classList.add("active");
  applyI18n();
  if (typeof renderWizard === "function") {
    const wb = document.getElementById("wizardBody");
    if (wb && wb.innerHTML.trim()) renderWizard();
  }
}

document.addEventListener("DOMContentLoaded", () => {
  document.querySelectorAll(".lang-btn").forEach(b => {
    b.addEventListener("click", () => setLanguage(b.dataset.lang));
  });
  setLanguage(CURRENT_LANG);
});